import { and, eq } from "drizzle-orm";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { assignLead, createLead, decideLostRequest, markLost, scheduleFollowUp, completeFollowUp } from "@/modules/leads/commands";
import { listNotifications, markAllRead, markRead, reminderMinutes, updateReminderMinutes } from "@/modules/notifications/service";
import { approvals, auditLogs, followUps, notifications, users } from "@/server/db/schema";
import { loadActor } from "@/server/auth/session-store";
import type { Database } from "@/server/db";
import type { Actor } from "@/server/auth/types";
import { AppError } from "@/server/errors";
import { connectTestDb, hasTestDb, leadInput, resetDb, seedFixture, type Fixture } from "../support/db";

const errorCode = async (p: Promise<unknown>) => {
  try {
    await p;
    return "ok";
  } catch (e) {
    if (e instanceof AppError) return e.code;
    throw e;
  }
};

describe.skipIf(!hasTestDb)("Notifications (PostgreSQL integration)", () => {
  let db: Database;
  let close: () => Promise<void>;
  let f: Fixture;
  let admin: Actor;
  let accountant: Actor;

  beforeAll(() => {
    ({ db, close } = connectTestDb());
  });
  afterAll(async () => close());
  beforeEach(async () => {
    await resetDb(db);
    f = await seedFixture(db);
    const mk = async (role: "admin" | "accountant", email: string) => {
      const [u] = await db.insert(users).values({ name: role === "admin" ? "Ada Admin" : "Acc", email, role, passwordHash: "x" }).returning();
      return loadActor(db, { id: u.id, name: u.name, email: u.email, role: u.role });
    };
    admin = await mk("admin", "admin@test.local");
    accountant = await mk("accountant", "acc@test.local");
  });

  const mine = async (actor: Actor) => (await listNotifications(db, actor)).rows;
  const lead = async (actor: Actor, overrides: Record<string, unknown> = {}) => {
    const r = await createLead(db, actor, leadInput(f, overrides));
    if (r.outcome !== "created") throw new Error("setup");
    return r.leadId;
  };

  describe("lead assignment and re-inquiry (Notify owner)", () => {
    it("notifies the new owner when someone else assigns a lead, never the actor", async () => {
      const id = await lead(f.actors.manager, { ownerId: f.actors.agent1.id });
      const [n] = await mine(f.actors.agent1);
      expect(n).toMatchObject({ type: "lead_assigned", link: `/dashboard/leads/${id}`, readAt: null });
      expect(n.title).toBe("Lead assigned to you · Test Lead");
      expect(n.body).toContain("assigned by Manager");
      // An agent creating their own lead, or a manager taking a lead, is not notified.
      await lead(f.actors.agent2);
      expect(await mine(f.actors.agent2)).toEqual([]);
      await assignLead(db, f.actors.manager, id, { ownerId: f.actors.manager.id });
      expect(await mine(f.actors.manager)).toEqual([]);
      // Reassigning to agent2 notifies agent2 once.
      await assignLead(db, f.actors.manager, id, { ownerId: f.actors.agent2.id });
      expect((await mine(f.actors.agent2)).map((x) => x.type)).toEqual(["lead_assigned"]);
    });

    it("notifies the owner of an existing lead when it is regenerated by someone else", async () => {
      const id = await lead(f.actors.agent1, { phoneNumber: "03009998877" });
      await createLead(db, admin, leadInput(f, { phoneNumber: "03009998877", onDuplicate: "regenerate" }));
      const rows = await mine(f.actors.agent1);
      expect(rows.map((r) => [r.type, r.link])).toEqual([["lead_regenerated", `/dashboard/leads/${id}`]]);
    });
  });

  describe("lost requests", () => {
    it("notifies the owner's team managers on a request, and the requester only on rejection", async () => {
      const id = await lead(f.actors.agent1);
      await markLost(db, f.actors.agent1, id, { lostReasonId: f.lostReasonId, note: "Budget" });
      const [m] = await mine(f.actors.manager);
      expect(m).toMatchObject({ type: "lost_requested", link: `/dashboard/leads/${id}` });
      expect(m.body).toContain("Agent A asked to mark lead");
      expect(await mine(admin)).toEqual([]); // admins are not in the documented recipients
      const [request] = await db.select().from(approvals).where(eq(approvals.leadId, id));
      await decideLostRequest(db, f.actors.manager, request.id, { approve: false, comment: "Call again" });
      const [r] = await mine(f.actors.agent1);
      expect(r).toMatchObject({ type: "lost_rejected", body: "Manager: Call again" });

      // Approval does not notify (the flow documents a notification on rejection only).
      const id2 = await lead(f.actors.agent1);
      await markLost(db, f.actors.agent1, id2, { lostReasonId: f.lostReasonId });
      const [req2] = await db.select().from(approvals).where(and(eq(approvals.leadId, id2)));
      await decideLostRequest(db, f.actors.manager, req2.id, { approve: true });
      expect((await mine(f.actors.agent1)).filter((x) => x.type === "lost_rejected")).toHaveLength(1);
    });

    it("sends nothing when the owner's team has no manager", async () => {
      const id = await lead(f.actors.outsideAgent);
      await markLost(db, f.actors.outsideAgent, id, { lostReasonId: f.lostReasonId });
      expect(await db.select().from(notifications)).toEqual([]);
    });
  });

  describe("follow-up reminders (FR-006 pop-up)", () => {
    it("are off until an admin sets the window, then remind the assignee once per due time", async () => {
      const id = await lead(f.actors.agent1);
      const now = new Date();
      await scheduleFollowUp(db, f.actors.agent1, id, { dueAt: new Date(now.getTime() + 20 * 60_000), note: "Call back" }, now);
      await scheduleFollowUp(db, f.actors.agent1, id, { dueAt: new Date(now.getTime() + 90 * 60_000) }, now);
      expect(await reminderMinutes(db)).toBeNull();
      expect(await mine(f.actors.agent1)).toEqual([]);

      await updateReminderMinutes(db, admin, { minutes: "30" });
      expect(await reminderMinutes(db)).toBe(30);
      for (let i = 0; i < 3; i++) await listNotifications(db, f.actors.agent1); // repeated polls
      const rows = await mine(f.actors.agent1);
      expect(rows.map((r) => [r.type, r.title, r.body])).toEqual([["follow_up_soon", "Follow-up soon · Test Lead", "Call back"]]);
      // Other users never get someone else's reminder.
      expect(await mine(f.actors.manager)).toEqual([]);

      // Rescheduling to a new time inside the window reminds again; completed follow-ups do not.
      const [fu] = await db.select().from(followUps).where(eq(followUps.note, "Call back"));
      await db.update(followUps).set({ dueAt: new Date(now.getTime() + 25 * 60_000) }).where(eq(followUps.id, fu.id));
      expect((await mine(f.actors.agent1)).filter((r) => r.type === "follow_up_soon")).toHaveLength(2);
      await completeFollowUp(db, f.actors.agent1, fu.id);
      await db.update(followUps).set({ dueAt: new Date(now.getTime() + 26 * 60_000) }).where(eq(followUps.id, fu.id));
      expect((await mine(f.actors.agent1)).filter((r) => r.type === "follow_up_soon")).toHaveLength(2);
    });

    it("lets only super admins and admins set the window, validates it and audits changes", async () => {
      for (const actor of [f.actors.manager, f.actors.agent1, f.actors.hr, accountant]) {
        expect(await errorCode(updateReminderMinutes(db, actor, { minutes: "15" }))).toBe("FORBIDDEN");
      }
      for (const v of ["0", "1441", "2.5", "abc"]) expect(await errorCode(updateReminderMinutes(db, admin, { minutes: v }))).toBe("VALIDATION_FAILED");
      expect(await updateReminderMinutes(db, f.actors.superAdmin, { minutes: "15" })).toEqual({ changed: true });
      expect(await updateReminderMinutes(db, admin, { minutes: "15" })).toEqual({ changed: false });
      expect(await updateReminderMinutes(db, admin, { minutes: "" })).toEqual({ changed: true });
      expect(await reminderMinutes(db)).toBeNull();
      const logs = await db.select().from(auditLogs).where(eq(auditLogs.entityId, "notifications.follow_up_reminder_minutes"));
      expect(logs.map((l) => [l.before, l.after])).toEqual(expect.arrayContaining([[{ value: "" }, { value: "15" }], [{ value: "15" }, { value: "" }]]));
    });
  });

  describe("reading", () => {
    it("lists only the user's own notifications, with unread counts and read state", async () => {
      await lead(f.actors.manager, { ownerId: f.actors.agent1.id });
      await lead(f.actors.manager, { ownerId: f.actors.agent1.id });
      await lead(f.actors.manager, { ownerId: f.actors.agent2.id });
      const a1 = await listNotifications(db, f.actors.agent1);
      expect([a1.total, a1.unread]).toEqual([2, 2]);
      await markRead(db, f.actors.agent1, a1.rows[0].id);
      expect((await listNotifications(db, f.actors.agent1)).unread).toBe(1);
      expect((await listNotifications(db, f.actors.agent1, { unread: "1" })).total).toBe(1);
      // Someone else's notification is not found; mark-all only touches the actor's own.
      const other = (await listNotifications(db, f.actors.agent2)).rows[0];
      expect(await errorCode(markRead(db, f.actors.agent1, other.id))).toBe("NOT_FOUND");
      expect(await errorCode(markRead(db, f.actors.agent1, "not-an-id"))).toBe("NOT_FOUND");
      expect(await markAllRead(db, f.actors.agent1)).toEqual({ marked: 1 });
      expect((await listNotifications(db, f.actors.agent2)).unread).toBe(1);
      // HR and accountants can read their (empty) list.
      expect((await listNotifications(db, f.actors.hr)).total).toBe(0);
      expect((await listNotifications(db, accountant)).total).toBe(0);
    });

    it("never stores a duplicate event or an external link", async () => {
      const base = { userId: f.actors.agent1.id, type: "lead_assigned" as const, title: "x", dedupeKey: "k" };
      await db.insert(notifications).values(base);
      await expect(db.insert(notifications).values(base)).rejects.toThrow();
      await expect(db.insert(notifications).values({ ...base, dedupeKey: "k2", link: "https://evil.example" })).rejects.toThrow();
    });
  });
});
